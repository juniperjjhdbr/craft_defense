package net.juujks.craft_defense.client.renderer;

import net.minecraft.util.Mth;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.MultiBufferSource;

import net.juujks.craft_defense.entity.WindChargeProjectileEntity;
import net.juujks.craft_defense.client.model.Modelbreeze_wind_charge;

import com.mojang.math.Axis;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.mojang.blaze3d.vertex.PoseStack;

public class WindChargeProjectileRenderer extends EntityRenderer<WindChargeProjectileEntity> {
	private static final ResourceLocation texture = ResourceLocation.parse("craft_defense:textures/entities/breeze_wind_charge.png");
	private final Modelbreeze_wind_charge model;

	public WindChargeProjectileRenderer(EntityRendererProvider.Context context) {
		super(context);
		model = new Modelbreeze_wind_charge(context.bakeLayer(Modelbreeze_wind_charge.LAYER_LOCATION));
	}

	@Override
	public void render(WindChargeProjectileEntity entityIn, float entityYaw, float partialTicks, PoseStack poseStack, MultiBufferSource bufferIn, int packedLightIn) {
		VertexConsumer vb = bufferIn.getBuffer(RenderType.entityCutout(this.getTextureLocation(entityIn)));
		poseStack.pushPose();
		poseStack.mulPose(Axis.YP.rotationDegrees(Mth.lerp(partialTicks, entityIn.yRotO, entityIn.getYRot()) - 90));
		poseStack.mulPose(Axis.ZP.rotationDegrees(90 + Mth.lerp(partialTicks, entityIn.xRotO, entityIn.getXRot())));
		model.setupAnim(entityIn, 0, 0, entityIn.tickCount + partialTicks, entityIn.getYRot(), entityIn.getXRot());
		model.renderToBuffer(poseStack, vb, packedLightIn, OverlayTexture.NO_OVERLAY);
		poseStack.popPose();
		super.render(entityIn, entityYaw, partialTicks, poseStack, bufferIn, packedLightIn);
	}

	@Override
	public ResourceLocation getTextureLocation(WindChargeProjectileEntity entity) {
		return texture;
	}
}